"""claude-duet-bridge: a cloud Claude hands jobs to Claude Code on your own computer (Windows or macOS) through
GitHub issues on a private repo, and your local agents hand questions back the same way.

    python bridge.py poll           one pass: answers on ask issues, then every open "job" issue opened by the owner
    python bridge.py jobs           the allowlist as this machine sees it
    python bridge.py approve N      run waiting issue N after the owner's yes typed in this terminal
    python bridge.py setup          create the labels on the jobs repo (once)
    python bridge.py config         print the resolved config (platform, repo, jobs, agents)

Everything specific to you lives in bridge.config.json next to this file (or the path in $BRIDGE_CONFIG); it is
gitignored. Start from bridge.config.example.json.

Safety, by construction:
- Only issues labeled "job" AND opened by the owner are read; anything else is never looked at.
- A job runs only when its name is in the local allowlist file AND in the config's "jobs". The allowlist file can sit
  in the jobs repo, but this script never pulls it, and the command each name runs lives only in the local config.
- Arguments are checked against each job's pattern and passed as argv, never through a shell.
- A job (or agent) marked needs_yes waits (label "waiting") until `approve N` is typed on this machine.
- "ask agent" runs headless Claude with read only tools, no MCP servers, a time limit and denied paths.
- Output is scrubbed of anything token shaped before it is posted.
"""
import json, os, platform, re, shutil, subprocess, sys
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONFIG_PATH = Path(os.environ.get("BRIDGE_CONFIG") or HERE / "bridge.config.json")
EMAIL = r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"
FOOTER = re.compile(r"\n\s*---\s*\n\s*_?Generated by .*\Z", re.S | re.I)  # Claude Code signs its issues like this
MARK = "<!-- from the PC -->"  # every post from this machine carries it; both sides post as the owner


def load_config() -> dict:
    if not CONFIG_PATH.exists():
        sys.exit(f"no config at {CONFIG_PATH}: copy bridge.config.example.json to bridge.config.json and fill it in")
    cfg = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    base = CONFIG_PATH.parent
    plat = (cfg.get("platform") or "auto").lower()
    if plat == "auto":
        plat = {"Windows": "windows", "Darwin": "mac"}.get(platform.system(), "linux")
    cfg["platform"] = plat
    cfg["root"] = (base / os.path.expanduser(cfg.get("root") or ".")).resolve()  # relative to the config, not the cwd
    rel = lambda p: (cfg["root"] / os.path.expanduser(p)).resolve() if p else None  # noqa: E731
    cfg["allowlist_path"] = rel(cfg.get("allowlist_file", "jobs.md"))
    cfg["answers_path"] = rel(cfg.get("answers_file"))
    cfg["data"] = rel(cfg.get("data_dir")) or HERE / "data"
    cfg.setdefault("machine_name", "the PC" if plat == "windows" else "the Mac")
    cfg.setdefault("owner_name", cfg["owner"])
    cfg.setdefault("timezone_label", "")
    cfg.setdefault("ask_label", "for-owner")
    cfg.setdefault("poll_minutes", 10)
    cfg.setdefault("jobs", {})
    cfg.setdefault("agents", {})
    cfg.setdefault("ask", {})
    return cfg


CFG = load_config() if __name__ == "__main__" or os.environ.get("BRIDGE_IMPORT_CONFIG") else None
REPO = OWNER = None
DATA = LOG = LOCK = LAST_POLL = SEEN = None


def init(cfg: dict):
    global CFG, REPO, OWNER, DATA, LOG, LOCK, LAST_POLL, SEEN
    CFG, REPO, OWNER = cfg, cfg["jobs_repo"], cfg["owner"].lower()
    DATA = cfg["data"]
    LOG, LOCK, LAST_POLL, SEEN = DATA / "runs.jsonl", DATA / "poll.lock", DATA / "last_poll.json", DATA / "seen.json"


# ---- platform -------------------------------------------------------------------------------------------------

def exe(name: str) -> str:
    """npm, npx and friends are .cmd shims on Windows; {python} is this interpreter."""
    if name == "python":
        return sys.executable
    if CFG["platform"] == "windows" and name in ("npm", "npx", "yarn", "pnpm"):
        return name + ".cmd"
    return shutil.which(name) or name


def claude_path_rule(p: str) -> str:
    """A path as a Claude Code permission rule: //c/Users/x/** on Windows, //Users/x/** on macOS."""
    p = os.path.expanduser(p).replace("\\", "/").rstrip("/")
    m = re.match(r"^([A-Za-z]):/(.*)$", p)
    if m:
        p = f"/{m.group(1).lower()}/{m.group(2)}"
    return "/" + p + "/**"


def detach_kwargs() -> dict:
    if CFG["platform"] == "windows":
        return {"creationflags": getattr(subprocess, "DETACHED_PROCESS", 0) | getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)}
    return {"start_new_session": True}


CMD_SPECIAL = re.compile(r'[&|<>^%!"()\r\n]')


def cmd_exe_refusal(cmd: list) -> str:
    """Windows hands .cmd and .bat files to cmd.exe even without a shell, and cmd.exe acts on these characters in an argument."""
    if cmd[0].lower().endswith((".cmd", ".bat")) and any(CMD_SPECIAL.search(tok) for tok in cmd[1:]):
        return f"{os.path.basename(cmd[0])} runs through cmd.exe on Windows, so its arguments can't hold & | < > ^ % ! \" ( ) or a line break"
    return ""


# ---- output ---------------------------------------------------------------------------------------------------

SCRUB = [
    (re.compile(r"\b(gh[opusr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,})"), "[token]"),
    (re.compile(r"\b(sk-[A-Za-z0-9_-]{16,}|xox[abpr]-[A-Za-z0-9-]{10,}|AKIA[0-9A-Z]{16}|ASIA[0-9A-Z]{16})"), "[token]"),
    (re.compile(r"(?i)(bearer\s+)[A-Za-z0-9._~+/=-]{12,}"), r"\1[token]"),
    (re.compile(r"(?i)\b(password|passwd|secret|token|api[_-]?key|access[_-]?key)(\s*[:=]\s*)\S+"), r"\1\2[hidden]"),
    (re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{5,}"), "[token]"),
]


def scrub(s: str) -> str:
    for rx, rep in SCRUB:
        s = rx.sub(rep, s)
    return s


def gh(*args, input_text=None) -> str:
    r = subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8", errors="replace", input=input_text)
    if r.returncode != 0:
        raise RuntimeError(f"gh {' '.join(args[:2])}: {r.stderr.strip()[:300]}")
    return r.stdout


def comment(n: int, body: str):
    gh("issue", "comment", str(n), "-R", REPO, "--body-file", "-", input_text=body + "\n\n" + MARK)


def label(n: int, add: str, remove: str = ""):
    args = ["issue", "edit", str(n), "-R", REPO, "--add-label", add]
    if remove:
        args += ["--remove-label", remove]
    gh(*args)


def log(rec: dict):
    DATA.mkdir(parents=True, exist_ok=True)
    rec["at"] = datetime.now().isoformat(timespec="seconds")
    with LOG.open("a", encoding="utf-8") as f:
        f.write(json.dumps(rec) + "\n")


def stamp() -> str:
    return f"{datetime.now():%Y-%m-%d %H:%M}" + (f" {CFG['timezone_label']}" if CFG["timezone_label"] else "")


def clean_body(body: str) -> str:
    return FOOTER.sub("", (body or "").replace("\r\n", "\n")).strip()


# ---- the two directions ---------------------------------------------------------------------------------------

def answers() -> list:
    """The owner's answers on open ask issues (label ask_label, opened by the local team): every comment without MARK
    is appended once to answers_file and the issue is labeled answered; whoever reads that file routes it and closes
    the issue. An answer is the owner's word on the question, never a yes to send, spend, delete or deploy."""
    if not CFG["answers_path"]:
        return []
    seen = set(json.loads(SEEN.read_text(encoding="utf-8"))) if SEEN.exists() else set()
    out = []
    for i in json.loads(gh("api", f"repos/{REPO}/issues?state=open&labels={CFG['ask_label']}&per_page=50") or "[]"):
        if (i.get("user") or {}).get("login", "").lower() != OWNER or not i.get("comments"):
            continue
        for c in json.loads(gh("api", f"repos/{REPO}/issues/{i['number']}/comments?per_page=100") or "[]"):
            body = (c.get("body") or "").strip()
            if c["id"] in seen or MARK in body or (c.get("user") or {}).get("login", "").lower() != OWNER:
                continue
            line = " ".join(clean_body(body).split())[:600]
            CFG["answers_path"].parent.mkdir(parents=True, exist_ok=True)
            with CFG["answers_path"].open("a", encoding="utf-8") as f:
                f.write(f"- {datetime.now():%Y-%m-%d %H:%M} {CFG['owner_name']} via the bridge #{i['number']} ({i['title'][:80]}): {line}\n")
            seen.add(c["id"])
            label(i["number"], "answered")
            out.append(f"#{i['number']} answered: {line[:120]}")
    DATA.mkdir(parents=True, exist_ok=True)
    SEEN.write_text(json.dumps(sorted(seen)), encoding="utf-8")
    return out


def allowed_names() -> set:
    """Names in the allowlist file, as bullets that start with the name in backticks: - `crm lookup`: ..."""
    p = CFG["allowlist_path"]
    if not p or not p.exists():
        return set()
    return {m.group(1).strip().lower() for m in re.finditer(r"^\s*[-*]\s+`([^`]+)`", p.read_text(encoding="utf-8"), re.M)}


def all_jobs() -> dict:
    """The config's jobs plus the two built in ones."""
    jobs = {k.lower(): v for k, v in CFG["jobs"].items()}
    jobs.setdefault("bridge status", {"what": "when this machine last polled, the jobs and the agent names (read only)", "special": "status"})
    if CFG["agents"]:
        jobs.setdefault("ask agent", {"what": "a question for one named agent, answered headless and read only; body line 1 = the agent name, line 2 on = the request",
                                      "arg": r"^\s*(?P<agent>[^\n]{2,40}?)\s*\n(?P<req>.{3,4000})$", "special": "ask"})
    return jobs


def open_jobs() -> list:
    # the REST list, not search: `gh issue list --author` goes through search, which misses new issues for a minute
    issues = [i for i in json.loads(gh("api", f"repos/{REPO}/issues?state=open&labels=job&per_page=50") or "[]") if "pull_request" not in i]
    for i in issues:
        i["author"] = i.get("user") or {}
    return [i for i in issues if (i["author"].get("login") or "").lower() == OWNER]


def agent_key(s: str) -> str:
    return " ".join(s.lower().replace("-", " ").replace("_", " ").split())


def reject(n: int, name: str, why: str) -> str:
    comment(n, why)
    label(n, "rejected")
    gh("issue", "close", str(n), "-R", REPO)
    log({"issue": n, "job": name, "result": "not allowed"})
    return f"#{n} '{name}': not allowed"


def wait_for_yes(n: int, name: str, why: str = "") -> str:
    comment(n, f"Waiting for {CFG['owner_name']}'s yes typed on {CFG['machine_name']} (bridge.py approve {n}){': ' + why if why else ''}.")
    label(n, "waiting")
    log({"issue": n, "job": name, "result": "waiting"})
    return f"#{n} '{name}': waiting on {CFG['owner_name']}'s yes"


def run_job(i: dict, approved: bool = False) -> str:
    n, name = i["number"], (i.get("title") or "").strip().lower()
    # the REST list can lag by a minute: re-read the issue so a job that just finished is never run twice
    fresh = json.loads(gh("issue", "view", str(n), "-R", REPO, "--json", "state,labels"))
    labels = {l["name"] for l in fresh.get("labels", [])}
    if fresh.get("state") != "OPEN" or {"done", "running", "failed", "rejected"} & labels:
        return f"#{n} already handled"
    if "waiting" in labels and not approved:
        return f"#{n} waiting on {CFG['owner_name']}'s yes"
    jobs = all_jobs()
    job = jobs.get(name)
    if job is None or name not in allowed_names():
        return reject(n, name, "not allowed")
    body = clean_body(i.get("body"))
    args = {}
    if job.get("arg"):
        m = re.match(job["arg"].replace("{EMAIL}", EMAIL), body, re.S)
        if not m:
            return fail(n, name, "the issue body does not match what this job takes: " + job["what"])
        args = {k: (v or "").strip() for k, v in m.groupdict().items()}
    for k, v in (job.get("defaults") or {}).items():
        args[k] = args.get(k) or v
    if job.get("needs_yes") and not approved:
        return wait_for_yes(n, name)
    if job.get("special") == "status":
        return finish(n, name, labels, status_text(jobs))
    if job.get("special") == "ask":
        key = agent_key(args["agent"])
        agent = {agent_key(k): v for k, v in CFG["agents"].items()}.get(key)
        if agent is None:
            return reject(n, name, f"not allowed: no agent called '{args['agent'][:40]}'. Names: " + ", ".join(CFG["agents"]))
        if agent.get("needs_yes") and not approved:
            return wait_for_yes(n, name, f"an answer from the {key} needs the owner's yes")
        timeout = int(CFG["ask"].get("timeout_seconds", 900))
        comment(n, f"Started: {key} is on it (up to {timeout // 60} minutes).")
        label(n, "running")
        DATA.mkdir(parents=True, exist_ok=True)
        with (DATA / f"ask-{n}.log").open("w", encoding="utf-8") as f:  # its own process: a slow agent holds nothing up
            subprocess.Popen([sys.executable, str(Path(__file__).resolve()), "ask-run", str(n)], cwd=str(CFG["root"]), stdout=f,
                             stderr=subprocess.STDOUT, env={**os.environ, "PYTHONIOENCODING": "utf-8"}, **detach_kwargs())
        log({"issue": n, "job": name, "result": "started", "agent": key})
        return f"#{n} '{name}': started ({key})"
    ctx = {"python": exe("python"), "npm": exe("npm"), "npx": exe("npx"), **args}
    cwd = (CFG["root"] / os.path.expanduser(job.get("cwd", "."))).resolve()
    parts = []
    cmds = [[tok.format(**ctx) for tok in argv] for argv in job["run"]]  # each token is a template; values are inserted, never re-parsed
    refusal = next(filter(None, map(cmd_exe_refusal, cmds)), "")
    if refusal:
        return fail(n, name, refusal)  # before any step runs
    for cmd in cmds:
        try:
            r = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, encoding="utf-8", errors="replace",
                               timeout=int(job.get("timeout_seconds", 300)), env={**os.environ, "PYTHONIOENCODING": "utf-8"})
        except Exception as e:  # noqa: BLE001
            return fail(n, name, f"{type(e).__name__}: {e}")
        if r.returncode != 0:
            return fail(n, name, f"exit {r.returncode}\n{(r.stderr or r.stdout).strip()[-1500:]}")
        parts.append(r.stdout.strip() or "(no output)")
    return finish(n, name, labels, "\n\n".join(parts))


def finish(n: int, name: str, labels: set, text: str, fence: bool = True) -> str:
    text = scrub(text)
    if len(text) > 6000:
        text = text[:6000] + "\n... (cut at 6000 characters)"
    comment(n, f"Done on {CFG['machine_name']}, {stamp()}.\n\n" + (f"```\n{text}\n```" if fence else text))
    label(n, "done", ",".join(x for x in ("waiting", "running") if x in labels))
    gh("issue", "close", str(n), "-R", REPO)
    log({"issue": n, "job": name, "result": "done"})
    return f"#{n} '{name}': done"


def fail(n: int, name: str, err: str) -> str:
    comment(n, "Failed.\n\n```\n" + scrub(err)[:3000] + "\n```")
    label(n, "failed")
    log({"issue": n, "job": name, "result": "failed", "error": scrub(err)[:300]})
    return f"#{n} '{name}': failed"


def status_text(jobs: dict) -> str:
    last = json.loads(LAST_POLL.read_text(encoding="utf-8")) if LAST_POLL.exists() else {}
    asks = json.loads(gh("api", f"repos/{REPO}/issues?state=open&labels={CFG['ask_label']}&per_page=50") or "[]")
    names = allowed_names()
    lines = [f"Last poll before this one: {last.get('at', 'never')}; {CFG['machine_name']} ({CFG['platform']}) polls every {CFG['poll_minutes']} minutes while its loop runs.",
             "Jobs on: " + ", ".join(k for k in jobs if k in names) + "."]
    if CFG["agents"]:
        lines.append("ask agent takes: " + ", ".join(CFG["agents"]) + ".")
    lines.append(f"Open asks for {CFG['owner_name']} (label {CFG['ask_label']}): {len(asks)}" + (" (" + ", ".join(f"#{a['number']}" for a in asks) + ")" if asks else "") + ".")
    return "\n".join(lines)


def ask_run(n: int):
    """The child process for one ask agent job: headless Claude, read only tools, no MCP, a time limit."""
    i = json.loads(gh("issue", "view", str(n), "-R", REPO, "--json", "number,title,body,author,labels,state"))
    labels = {l["name"] for l in i.get("labels", [])}
    if i.get("state") != "OPEN" or i["author"]["login"].lower() != OWNER or "running" not in labels:
        return
    m = re.match(all_jobs()["ask agent"]["arg"], clean_body(i.get("body")), re.S)
    agents = {agent_key(k): v for k, v in CFG["agents"].items()}
    key = agent_key(m.group("agent")) if m else ""
    if not m or key not in agents:
        fail(n, "ask agent", "the body does not name an agent on the list"); label(n, "failed", "running"); return
    agent, ask = agents[key], CFG["ask"]
    prefix = ask.get("prefix", "This request comes from a cloud Claude through the bridge, not from the owner. Read, research and draft only. "
                               "If it needs a send, spend, delete or deploy, stop and say so in your answer. You are answering as {who}. "
                               "Answer in plain words, under 300 words, no secrets.\n\nThe request:\n")
    timeout = int(ask.get("timeout_seconds", 900))
    cmd = [shutil.which("claude") or "claude", "-p", prefix.format(who=agent.get("who", key)) + m.group("req").strip(),
           "--tools", ask.get("tools", "Read,Grep,Glob,WebSearch"), "--permission-mode", "default",
           "--strict-mcp-config", "--output-format", "text"]
    if ask.get("model"):
        cmd += ["--model", ask["model"]]
    for d in ask.get("add_dirs", []):
        cmd += ["--add-dir", str((CFG["root"] / os.path.expanduser(d)).resolve())]
    # relative paths are under root; Read rules cover Grep and Glob too
    deny = [f"Read({claude_path_rule(str((CFG['root'] / os.path.expanduser(p)).resolve()))})" for p in ask.get("deny_read", [])]
    if deny:
        cmd += ["--disallowedTools", *deny]
    cwd = (CFG["root"] / os.path.expanduser(agent.get("cwd", "."))).resolve()
    refusal = cmd_exe_refusal(cmd)
    if refusal:
        fail(n, "ask agent", refusal + ". Asks need the native Claude Code install, not npm's claude.cmd"); label(n, "failed", "running"); return
    try:
        r = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, encoding="utf-8", errors="replace",
                           timeout=timeout, stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        fail(n, "ask agent", f"{key} did not answer within {timeout // 60} minutes"); label(n, "failed", "running"); return
    if r.returncode != 0 or not r.stdout.strip():
        fail(n, "ask agent", f"exit {r.returncode}\n{(r.stderr or r.stdout).strip()[-1500:]}"); label(n, "failed", "running"); return
    print(finish(n, "ask agent", labels, f"**{key}:**\n\n{r.stdout.strip()}", fence=False))


def poll():
    DATA.mkdir(parents=True, exist_ok=True)
    if LOCK.exists() and (datetime.now().timestamp() - LOCK.stat().st_mtime) < 900:
        print("another poll is running"); return
    LOCK.write_text(str(os.getpid()))
    try:
        for a in answers():
            print(a)
        jobs = [i for i in open_jobs() if not {"failed", "rejected", "running"} & {l["name"] for l in i.get("labels", [])}]
        if not jobs:
            print("no new jobs"); return
        for i in sorted(jobs, key=lambda x: x["number"]):
            try:
                print(run_job(i))
            except Exception as e:  # noqa: BLE001
                print(f"#{i['number']}: {e}")
    finally:
        LAST_POLL.write_text(json.dumps({"at": stamp()}), encoding="utf-8")
        LOCK.unlink(missing_ok=True)


def main():
    init(CFG or load_config())
    cmd = sys.argv[1] if len(sys.argv) > 1 else "poll"
    if cmd == "poll":
        poll()
    elif cmd == "jobs":
        names = allowed_names()
        for k, v in all_jobs().items():
            print(f"{'on ' if k in names else 'off'}  {k:26} {'needs yes  ' if v.get('needs_yes') else ''}{v['what']}")
    elif cmd == "approve":
        n = int(sys.argv[2])
        i = json.loads(gh("issue", "view", str(n), "-R", REPO, "--json", "number,title,body,author,labels,state"))
        if i.get("state") != "OPEN" or i["author"]["login"].lower() != OWNER:
            sys.exit(f"#{n} is not an open issue by {OWNER}")
        print(run_job(i, approved=True))
    elif cmd == "ask-run":
        ask_run(int(sys.argv[2]))
    elif cmd == "config":
        print(f"platform {CFG['platform']}  repo {REPO}  owner {OWNER}  root {CFG['root']}")
        print(f"allowlist {CFG['allowlist_path']}  answers {CFG['answers_path']}  data {DATA}")
        print("jobs: " + ", ".join(all_jobs()) + "\nagents: " + (", ".join(CFG["agents"]) or "none"))
    elif cmd == "setup":
        for name, color, desc in [("job", "1d76db", "a job for the local machine"), ("done", "0e8a16", "finished"),
                                  ("failed", "d93f0b", "failed, see the comment"), ("rejected", "000000", "not on the allowlist"),
                                  ("waiting", "fbca04", "waiting on the owner's yes typed locally"),
                                  (CFG["ask_label"], "5319e7", "the local team asks the owner"),
                                  ("answered", "c5def5", "the owner answered"), ("running", "bfdadc", "an agent is working on it")]:
            gh("label", "create", name, "-R", REPO, "--color", color, "--description", desc, "--force")
        print("labels ready")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
